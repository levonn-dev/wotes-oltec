// Package emit renders a converted map as assembler, a report for people and a Ninja depfile.
package emit

import (
	"encoding/binary"
	"fmt"
	"strings"

	"github.com/levonn-dev/wotes-oltec/wotes-tiled/internal/convert"
	"github.com/levonn-dev/wotes-oltec/wotes-tiled/internal/rom"
)

// Assembler renders the tables as GNU as source for the m68k target. ROM data enters only as .incbin
// offsets and chunk addresses; the only pixel data written is the map's new tiles.
func Assembler(res *convert.Result, source string) string {
	var sb strings.Builder
	n := res.Name
	fmt.Fprintf(&sb, "| Generated by wotes-tiled from %s. Do not edit.\n", source)
	sb.WriteString("    .section .rodata\n    .balign 2\n")
	globals := []string{n + "_front", n + "_ground", n + "_blocks", n + "_metatiles", n + "_tiles"}
	for _, p := range res.Places {
		globals = append(globals, n+"_place_"+p.Name)
	}
	if len(res.Triggers) > 0 {
		globals = append(globals, n+"_triggers")
	}
	if len(res.Texts) > 0 {
		globals = append(globals, n+"_texts")
	}
	if len(res.Figures) > 0 {
		globals = append(globals, n+"_figures")
	}
	if len(res.FigureColours) > 0 {
		globals = append(globals, n+"_figure_colours")
	}
	if len(res.Spawns) > 0 {
		globals = append(globals, n+"_spawns", n+"_spawn_grid")
	}
	if len(res.Entrances) > 0 {
		globals = append(globals, n+"_entrance_regions", n+"_entrance_points")
	}
	if res.Levels != nil {
		globals = append(globals, n+"_levels", n+"_level_directory", n+"_stairs")
	}
	fmt.Fprintf(&sb, "    .globl  %s\n", strings.Join(globals, ", "))
	fmt.Fprintf(&sb, "\n%s_front:\n", n)
	words(&sb, res.Front[:])
	fmt.Fprintf(&sb, "%s_ground:\n", n)
	words(&sb, res.Ground[:])
	fmt.Fprintf(&sb, "\n%s_blocks:\n", n)
	for _, b := range res.Blocks {
		words(&sb, b[:])
	}
	fmt.Fprintf(&sb, "\n%s_metatiles:\n", n)
	fmt.Fprintf(&sb, "    .incbin \"clean.md\", 0x%X, %d\n", res.Base.Metatiles, res.Base.MetaCount*18)
	for _, m := range res.Generated {
		ws := make([]uint16, len(m))
		for i, w := range m {
			ws[i] = uint16(w)
		}
		words(&sb, ws)
	}
	fmt.Fprintf(&sb, "\n%s_tiles:\n", n)
	for _, ch := range res.Chunks {
		switch ch.Kind {
		case "base":
			fmt.Fprintf(&sb, "    .short  0x%X\n    .long   0x%06X\n", ch.Count, ch.Source)
		case "borrowed":
			fmt.Fprintf(&sb, "    .short  0x%X\n    .long   0x%06X + 32 * 0x%X\n", ch.Count, ch.Source-32*ch.First, ch.First)
		case "new":
			fmt.Fprintf(&sb, "    .short  0x%X\n    .long   %s_tile_data\n", ch.Count, n)
		}
	}
	sb.WriteString("    .short  0\n")
	if len(res.NewTiles) > 0 {
		fmt.Fprintf(&sb, "\n%s_tile_data:\n", n)
		for _, t := range res.NewTiles {
			tileBytes(&sb, t)
		}
	}
	if len(res.Places) > 0 {
		sb.WriteString("\n")
	}
	for _, p := range res.Places {
		fmt.Fprintf(&sb, "%s_place_%s:\n    .short  %d, %d, %d, %d\n", n, p.Name, p.X0, p.Y0, p.X1, p.Y1)
	}
	objects(&sb, res)
	sb.WriteString("\n    .section .note.GNU-stack,\"\",%progbits\n")
	return sb.String()
}

// words writes values eight per line.
func words(sb *strings.Builder, ws []uint16) {
	for i := 0; i < len(ws); i += 8 {
		parts := make([]string, 0, 8)
		for _, w := range ws[i:min(i+8, len(ws))] {
			parts = append(parts, fmt.Sprintf("0x%04X", w))
		}
		fmt.Fprintf(sb, "    .short  %s\n", strings.Join(parts, ", "))
	}
}

// tileBytes writes one tile's 32 bytes as two lines of sixteen.
func tileBytes(sb *strings.Builder, t rom.Tile) {
	for half := 0; half < 2; half++ {
		parts := make([]string, 0, 16)
		for i := 0; i < 16; i++ {
			p := (half*16 + i) * 2
			parts = append(parts, fmt.Sprintf("0x%02X", t[p]<<4|t[p+1]))
		}
		fmt.Fprintf(sb, "    .byte   %s\n", strings.Join(parts, ", "))
	}
}

// objects writes the tables of the map's object layers: the trigger records, the texts they show, the
// figure records, the figures' palette line, the spawn areas, the entrance tables and the dungeon tables.
func objects(sb *strings.Builder, res *convert.Result) {
	n := res.Name
	if len(res.Triggers) > 0 {
		fmt.Fprintf(sb, "\n%s_triggers:\n", n)
		events := 0
		for _, t := range res.Triggers {
			fmt.Fprintf(sb, "    .short  0x%04X, 0x%04X, 0x%04X, 0x%04X | %s\n    .byte   %d, %d\n", t.Y0, t.Y1, t.X0, t.X1, t.Name, t.Level, t.Kind)
			switch t.Kind {
			case convert.TriggerShop:
				fmt.Fprintf(sb, "    .long   %d\n", t.Shop)
			case convert.TriggerEvent:
				fmt.Fprintf(sb, "    .long   %s_event_%d\n", n, events)
				events++
			default:
				fmt.Fprintf(sb, "    .long   %s_text_%d\n", n, t.Text)
			}
		}
		sb.WriteString("    .short  0xFFFF\n")
		// An event's block: its text, its after-text or 0, then the picture, the item and the flag, padded to a word.
		events = 0
		for _, t := range res.Triggers {
			if t.Kind != convert.TriggerEvent {
				continue
			}
			after := "0"
			if t.Event.After >= 0 {
				after = fmt.Sprintf("%s_text_%d", n, t.Event.After)
			}
			fmt.Fprintf(sb, "%s_event_%d:\n    .long   %s_text_%d, %s\n    .byte   %d, %d, 0x%02X, 0\n", n, events, n, t.Text, after, t.Event.Picture, t.Event.Item, t.Event.Flag)
			events++
		}
	}
	if len(res.Texts) > 0 {
		fmt.Fprintf(sb, "\n%s_texts:\n", n)
		for i, lines := range res.Texts {
			enc := rom.EncodeMessage(lines)
			fmt.Fprintf(sb, "%s_text_%d:\n    .byte   %d, %d\n", n, i, enc[0], enc[1])
			for _, l := range lines {
				sb.WriteString(asciz(l))
			}
			sb.WriteString("    .byte   0\n")
		}
		sb.WriteString("    .balign 2\n")
	}
	if len(res.Figures) > 0 {
		fmt.Fprintf(sb, "\n%s_figures:\n", n)
		for _, f := range res.Figures {
			r := f.Record(convert.FigureLine)
			fmt.Fprintf(sb, "    .short  0x%04X, 0x%04X | %s\n    .long   0x%08X, 0x%08X\n    .short  %d\n", f.X, f.Y, f.Name, binary.BigEndian.Uint32(r[4:]), binary.BigEndian.Uint32(r[8:]), f.Slot)
			parts := make([]string, rom.DefinitionSize)
			for i, b := range r[14:] {
				parts[i] = fmt.Sprintf("0x%02X", b)
			}
			fmt.Fprintf(sb, "    .byte   %s\n", strings.Join(parts, ", "))
		}
		sb.WriteString("    .long   0\n")
	}
	if len(res.FigureColours) > 0 {
		fmt.Fprintf(sb, "\n%s_figure_colours:\n", n)
		words(sb, res.FigureColours)
	}
	spawns(sb, res)
	entrances(sb, res)
	levels(sb, res)
}

// asciz writes one NUL-terminated string, escaping what the assembler would misread.
func asciz(s string) string {
	return "    .asciz  \"" + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + "\"\n"
}

// spawns writes a record for each spawn area (the frames between two rolls, 0 for the game's own; 1 when a
// group is tried on every side of the party; its list, or 0 when nothing spawns), the lists of eight
// entries, and the grid: its rectangle in metatile cells, then one byte a cell, 0 or an area's number from 1.
func spawns(sb *strings.Builder, res *convert.Result) {
	if len(res.Spawns) == 0 {
		return
	}
	n := res.Name
	fmt.Fprintf(sb, "\n%s_spawns:\n", n)
	for i, s := range res.Spawns {
		all := 0
		if s.All {
			all = 1
		}
		fmt.Fprintf(sb, "    .short  %d, %d | %s\n", s.Pause, all, s.Name)
		if len(s.Monsters) > 0 {
			fmt.Fprintf(sb, "    .long   %s_spawn_%d\n", n, i+1)
		} else {
			sb.WriteString("    .long   0\n")
		}
	}
	for i, s := range res.Spawns {
		if len(s.Monsters) == 0 {
			continue
		}
		fmt.Fprintf(sb, "%s_spawn_%d:\n", n, i+1)
		for _, m := range s.Monsters {
			fmt.Fprintf(sb, "    .byte   0x%02X, 0x%02X, %d, %d | %s\n", m.ID, m.Min<<4|m.Max, m.Level, m.Affinity, m.Name)
		}
	}
	g := res.SpawnGrid
	fmt.Fprintf(sb, "%s_spawn_grid:\n    .short  %d, %d, %d, %d\n", n, g.X, g.Y, g.W, g.H)
	for y := 0; y < g.H; y++ {
		parts := make([]string, g.W)
		for x := range parts {
			parts[x] = fmt.Sprint(g.Cells[y*g.W+x])
		}
		fmt.Fprintf(sb, "    .byte   %s\n", strings.Join(parts, ", "))
	}
	sb.WriteString("    .balign 2\n")
}
